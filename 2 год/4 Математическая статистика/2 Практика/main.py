# -------------------------------------------------
# ЗАДАНИЕ: Первичная обработка выборки
# -------------------------------------------------
# ШАГ 0: Загрузите свою выборку (замените номер файла на ваш вариант)
data = np.loadtxt('variant_5.csv', delimiter=',')

print(f"Объём выборки: n = {len(data)}")
print()

# -------------------------------------------------
# ШАГ 1: Вариационный ряд
# -------------------------------------------------
# ДОПОЛНИТЕ КОД:
# sorted_data = ...
# Выведите первые 5 и последние 5 значений вариационного ряда
sorted_data = np.sort(data)
print("Вариационный ряд:")
print("  первые 5:", sorted_data[:5])
print("  последние 5:", sorted_data[-5:])
print()


# -------------------------------------------------
# ШАГ 2: Выборочные оценки
# -------------------------------------------------
# ДОПОЛНИТЕ КОД:
# x_bar = ...       # среднее
# s2 = ...          # дисперсия (несмещённая!)
# s = ...           # стандартное отклонение
# median = ...      # медиана
# x_min = ...       # минимум
# x_max = ...       # максимум

x_bar = np.mean(data)                 # среднее
s2 = np.var(data, ddof=1)             # дисперсия (несмещённая!)
s = np.sqrt(s2)                       # стандартное отклонение
median = np.median(data)              # медиана
x_min = np.min(data)                  # минимум
x_max = np.max(data)                  # максимум

print("Выборочные оценки:")
print(f"  Среднее:      x̄ = {x_bar:.6f}")
print(f"  Дисперсия:    s² = {s2:.6f}")
print(f"  Ст. откл.:    s = {s:.6f}")
print(f"  Медиана:      x̃ = {median:.6f}")
print(f"  Размах:       [{x_min:.1f}, {x_max:.1f}]")
print()

# -------------------------------------------------
# ШАГ 3: Правило Скотта и гистограмма
# -------------------------------------------------
# ДОПОЛНИТЕ КОД:
# n = len(data)
# s = ...  # уже посчитано в Шаге 2
# h = 3.5 * s * n**(-1/3)
# k = ...  # число интервалов (округлить вверх)

n = len(data)
h = 3.5 * s * n**(-1/3)
k = (x_max - x_min) / h

print(f"Правило Скотта:")
print(f"  Ширина интервала: h = {h:.2f}")
print(f"  Число интервалов: k = {k}")
print()

# Постройте ДВЕ гистограммы рядом:
#  а) с числом интервалов по Скотту
#  б) с фиксированным числом интервалов = 5
# Добавьте на каждую вертикальную линию со средним значением

print("гистограммы")
print("  а) с числом интервалов по Скотту")
plt.hist(data, bins=int(np.round(k, decimals=0)), color='skyblue', edgecolor='black', alpha=0.7)
plt.show()
print("  б) с фиксированным числом интервалов = 5")
plt.hist(data, bins=5, color='skyblue', edgecolor='black', alpha=0.7)
plt.show()

# -------------------------------------------------
# ШАГ 4: Полигон частот
# -------------------------------------------------
# ДОПОЛНИТЕ КОД:
# Постройте полигон частот для интервального ряда
# (используйте те же интервалы, что и в гистограмме по Скотту)

print("полигон частот с числом интервалов по Скотту")
counts, bins, patches = plt.hist(data, bins=int(np.round(k, decimals=0)), alpha=0) 
bin_centers = (bins[:-1] + bins[1:]) / 2
plt.plot(bin_centers, counts, '-o', color='red', linewidth=2)
plt.xlabel('Значения')
plt.ylabel('Частота')
plt.show()


# -------------------------------------------------
# ШАГ 5: Эмпирическая функция распределения
# -------------------------------------------------
# ДОПОЛНИТЕ КОД:
# Постройте график ЭФР с пунктирными вертикалями в точках скачков
# и точками на горизонтальных участках

